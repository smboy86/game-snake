import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), "utf8");

const phaserPath = path.join(root, "vendor", "phaser.min.js");
const phaser = fs.readFileSync(phaserPath, "utf8");
const styles = read("styles.css");
const gameCode = read("main.js");
const bgm = fs.readFileSync(path.join(root, "assets", "audio", "music", "bgm.mp3"));
const gameAssets = {
  bgm: `data:audio/mpeg;base64,${bgm.toString("base64")}`,
};

const html = `<!doctype html>
<html lang="ko">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no" />
    <title>Snake Game</title>
    <style>${styles}</style>
  </head>
  <body>
    <main id="game-shell" aria-label="Snake Game">
      <div id="game"></div>
    </main>
    <script>${phaser}</script>
    <script>window.__snake_assets = ${JSON.stringify(gameAssets)};</script>
    <script>${gameCode}</script>
  </body>
</html>`;

const generatedDir = path.join(root, "src", "generated");
fs.mkdirSync(generatedDir, { recursive: true });

const output = `// This file is generated by scripts/bundle-game-html.mjs.
// Do not edit directly; update index.html, styles.css, main.js, or Phaser dependency instead.

export const gameHtml = ${JSON.stringify(html)};
`;

fs.writeFileSync(path.join(generatedDir, "gameHtml.ts"), output);
console.log(`Generated src/generated/gameHtml.ts (${Buffer.byteLength(html, "utf8")} bytes)`);
